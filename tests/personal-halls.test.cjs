const fs=require('node:fs');
const vm=require('node:vm');
const assert=require('node:assert/strict');
const source=fs.readFileSync(process.argv[2]||'app.js','utf8');
const ctx=vm.createContext({state:{halls:[],events:[]},legacyHalls:[],editing:null,route:()=>null});
vm.runInContext(source.slice(source.indexOf('function hallById('),source.indexOf('function emptyBlocks(')),ctx);
ctx.legacyHalls=[{id:'shared',name:'Старое название'}];
ctx.state.halls=[{id:'shared',name:'Личное название'},{id:'mine',name:'Мой зал'}];
const old={id:'old',halls:['shared']};
assert.equal(ctx.evHalls(old)[0].name,'Старое название');
const event={id:'event',halls:['foreign','shared'],hallNames:{foreign:'Зал коллеги',shared:'Название в ТЗ'}};
assert.equal(ctx.evHalls(event)[0].name,'Зал коллеги');
assert.equal(ctx.evHalls(event)[1].name,'Название в ТЗ');
assert.deepEqual(Array.from(ctx.pickerHalls(event),h=>h.id),['foreign','shared','mine']);
assert.deepEqual(Array.from(ctx.pickerHalls({halls:[],_new:true}),h=>h.id),['shared','mine']);
const fresh={halls:['mine'],_new:true};ctx.snapshotHalls(fresh);ctx.state.halls=[];
assert.equal(ctx.evHalls(fresh)[0].name,'Мой зал');
ctx.snapshotHalls(old);ctx.legacyHalls=[];
assert.equal(ctx.evHalls(old)[0].name,'Старое название');
assert.equal(ctx.evHalls({halls:['unknown']})[0].id,'unknown');
console.log('PASS: own picker, colleague halls, legacy names, snapshot stability, missing IDs');
