begin;
do $$
declare eid text:='audit-bot-'||gen_random_uuid(); cid bigint:=-800000000000000-floor(random()*10000000000000)::bigint; upd bigint:=800000000000000+floor(random()*10000000000000)::bigint; qid bigint; lease_id uuid:=gen_random_uuid(); n int;
begin
 insert into public.events(id,data) values(eid,'{"title":"Bot test","status":"prep","halls":[],"blocks":{}}');
 perform public.tg_command(upd,cid,'/start',eid,false);
 assert exists(select from tz_telegram.subs where event=eid and chat=cid),'Event subscription missing';
 select count(*) into n from tz_telegram.outbox where chat=cid;
 perform public.tg_command(upd,cid,'/start',eid,false);
 assert (select count(*) from tz_telegram.outbox where chat=cid)=n,'Update deduplication failed';
 perform public.tg_command(upd+1,cid,'/shop_on','',false);
 assert exists(select from tz_telegram.shop_subs where chat=cid),'Shop subscription missing';
 perform public.tg_command(upd+2,cid,'/shop_off','',false);
 assert not exists(select from tz_telegram.shop_subs where chat=cid),'Shop unsubscribe failed';
 perform public.tg_command(upd+3,cid,'/shop_on','',false);
 perform public.tg_command(upd+4,cid,'/stop','',false);
 assert not exists(select from tz_telegram.subs where chat=cid),'Stop kept event subscription';
 assert not exists(select from tz_telegram.shop_subs where chat=cid),'Stop kept shop subscription';
 perform public.tg_command(upd+5,cid,'/start','',true);
 assert exists(select from tz_telegram.admin_chats where chat=cid),'Admin subscription missing';
 perform public.tg_command(upd+6,cid,'/stop','',false);
 assert not exists(select from tz_telegram.admin_chats where chat=cid),'Stop kept admin subscription';
 update public.events set data=data||'{"deletedAt":"2026-11-17"}' where id=eid;
 perform public.tg_command(upd+7,cid,'/start',eid,false);
 assert not exists(select from tz_telegram.subs where event=eid and chat=cid),'Subscribed to deleted event';
 insert into tz_telegram.outbox(chat,kind,message,lease) values(cid,'reply','test',lease_id) returning id into qid;
 perform public.tg_finish(qid,gen_random_uuid(),200,0);
 assert exists(select from tz_telegram.outbox where id=qid),'Wrong lease removed job';
 perform public.tg_finish(qid,lease_id,429,60);
 assert exists(select from tz_telegram.outbox where id=qid and lease is null and due>=now()+interval '59 seconds'),'429 retry not scheduled';
 update tz_telegram.outbox set lease=lease_id where id=qid;
 perform public.tg_finish(qid,lease_id,200,0);
 assert not exists(select from tz_telegram.outbox where id=qid),'Successful job not removed';
 insert into tz_telegram.subs(event,chat) values(eid,cid);
 insert into tz_telegram.outbox(chat,kind,message,lease) values(cid,'reply','test',lease_id) returning id into qid;
 perform public.tg_finish(qid,lease_id,403,0);
 assert not exists(select from tz_telegram.subs where chat=cid),'403 left subscriptions';
 assert not exists(select from tz_telegram.outbox where chat=cid),'403 left messages';
end $$;
rollback;
